function examplePlan(numbers, offices = []) {
  const base = FLOOR_PLANS['10-5'];
  const slot = (no) => base.rooms.find((r) => r.no === no).points;
  const wide = ['504', '503', '502', '505', '501'].map(slot);
  const small = ['506', '507', '508', '509', '510'].map(slot);
  const rooms = [
    ...numbers.map((no, k) => room(no, '강의실', undefined, true, wide[k])),
    ...offices.map(([no, name, en], k) => room(no, name, en, false, small[k])),
  ];
  const unused = [...wide.slice(numbers.length), ...small.slice(offices.length)];
  return { ...base, example: true, rooms, areas: [...base.areas, ...unused.map((points) => area('', points))] };
}
